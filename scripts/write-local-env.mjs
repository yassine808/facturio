#!/usr/bin/env node
/**
 * Writes .env.local from the running local Supabase stack (`pnpm db:env`).
 * Requires `pnpm db:start` to have been run first.
 * Fails loudly if Supabase is not running or the status output is unexpected.
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

let raw;
try {
  raw = execSync("npx supabase status -o env", { encoding: "utf8" });
} catch (e) {
  console.error("db:env FAILED — is the local stack running? Run: pnpm db:start");
  console.error(String(e.stdout || e.message));
  process.exit(1);
}

// Parse KEY=VALUE lines, tolerant of `export KEY=...` and surrounding quotes.
const vars = {};
for (const line of raw.split(/\r?\n/)) {
  const m = line.match(/^\s*(?:export\s+)?([A-Z0-9_]+)=(.*)$/);
  if (m) vars[m[1]] = m[2].trim().replace(/^["']|["']$/g, "");
}

const url = vars.API_URL || vars.SUPABASE_URL || vars.SUPABASE_LOCAL_URL;
const anon = vars.ANON_KEY || vars.SUPABASE_ANON_KEY;
if (!url || !anon) {
  console.error(
    "db:env FAILED — could not find API_URL and ANON_KEY in `supabase status -o env`.",
  );
  console.error("Keys found:", Object.keys(vars).join(", ") || "(none)");
  process.exit(1);
}

const envLocal = [
  "# Generated by `pnpm db:env` — local Supabase values. Never commit this file.",
  `NEXT_PUBLIC_SUPABASE_URL=${url}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${anon}`,
  `NEXT_PUBLIC_SITE_URL=http://localhost:3000`,
  "",
].join("\n");

writeFileSync(".env.local", envLocal);
console.log("db:env OK — wrote .env.local from local Supabase.");
